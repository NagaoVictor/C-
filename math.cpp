#include <iostream>
#include <cmath> // Necessário para funções matemáticas

int main() {
    std::cout << "Raiz quadrada: " << sqrt(64.0) << "\n";      // 8
    std::cout << "Potencia (2^3): " << pow(2.0, 3.0) << "\n";  // 8
    std::cout << "Valor absoluto: " << abs(-15) << "\n";       // 15
    std::cout << "Arredondamento para cima: " << ceil(4.2) << "\n"; // 5
    
    return 0;
}